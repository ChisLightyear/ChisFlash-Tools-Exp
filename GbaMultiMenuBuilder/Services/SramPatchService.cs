    public SramPatchResult TryApply(byte[] romData)
    {
        ArgumentNullException.ThrowIfNull(romData);

        if (!TryFindPatchSet(romData, out var patchSet, out var identifier))
        {
            return new SramPatchResult(romData, false, null);
        }

        var patchedData = (byte[])romData.Clone();
        patchSet.Apply(patchedData);
        return new SramPatchResult(patchedData, true, identifier);
    }

    public string? DetectPatchTarget(string romPath)
    {
        var romData = File.ReadAllBytes(romPath);
        return DetectPatchTarget(romData);
    }

    public string? DetectPatchTarget(ReadOnlySpan<byte> romData)
    {
        return TryFindPatchSet(romData, out _, out var identifier) ? identifier : null;
    }

    public string? DetectAppliedPatchTarget(string romPath)
    {
        var romData = File.ReadAllBytes(romPath);
        return DetectAppliedPatchTarget(romData);
    }

    public string? DetectAppliedPatchTarget(ReadOnlySpan<byte> romData)
    {
        foreach (var candidate in PatchSets)
        {
            if (!candidate.TryMatchAppliedPatch(romData, out var identifier))
            {
                continue;
            }

            return identifier;
        }

        return null;
    }

    private static bool TryFindPatchSet(
        ReadOnlySpan<byte> romData,
        out PatchSetDefinition patchSet,
        out string identifier)
    {
        foreach (var candidate in PatchSets)
        {
            if (!candidate.TryMatchIdentifier(romData, out identifier))
            {
                continue;
            }

            patchSet = candidate;
            return true;
        }

        patchSet = null!;
        identifier = string.Empty;
        return false;
    }

