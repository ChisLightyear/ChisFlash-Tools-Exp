    private static bool[] CreateMask(int length, params int[] wildcardIndexes)
    {
        var mask = new bool[length];
        foreach (var index in wildcardIndexes)
        {
            mask[index] = true;
        }

        return mask;
    }

    private static int FindPattern(ReadOnlySpan<byte> data, ReadOnlySpan<byte> marker, bool[]? markerMask = null)
    {
        if (marker.Length == 0 || data.Length < marker.Length)
        {
            return -1;
        }

        var useMask = markerMask is not null && markerMask.Length == marker.Length;
        for (var start = 0; start <= data.Length - marker.Length; start++)
        {
            var matched = true;
            for (var offset = 0; offset < marker.Length; offset++)
            {
                if (useMask && markerMask![offset])
                {
                    continue;
                }

                if (data[start + offset] != marker[offset])
                {
                    matched = false;
                    break;
                }
            }

            if (matched)
            {
                return start;
            }
        }

        return -1;
    }

    private sealed record PatchDefinition(byte[] Marker, byte[] Replace, bool[]? MarkerMask = null);

    private sealed class PatchSetDefinition(string[] identifiers, PatchDefinition[] patches)
    {
        private readonly (byte[] Pattern, string Identifier)[] _identifierPatterns = identifiers
            .Select(identifier => (Encoding.ASCII.GetBytes(identifier), identifier))
            .ToArray();

        public bool TryMatchIdentifier(ReadOnlySpan<byte> romData, out string identifier)
        {
            foreach (var (pattern, name) in _identifierPatterns)
            {
                if (FindPattern(romData, pattern) < 0)
                {
                    continue;
                }

                identifier = name;
                return true;
            }

            identifier = string.Empty;
            return false;
        }

        public bool TryMatchAppliedPatch(ReadOnlySpan<byte> romData, out string identifier)
        {
            if (!TryMatchIdentifier(romData, out identifier))
            {
                return false;
            }

            var missingOriginalMarker = false;
            foreach (var patch in patches)
            {
                if (FindPattern(romData, patch.Replace) < 0)
                {
                    identifier = string.Empty;
                    return false;
                }

                if (!missingOriginalMarker && FindPattern(romData, patch.Marker, patch.MarkerMask) < 0)
                {
                    missingOriginalMarker = true;
                }
            }

            if (!missingOriginalMarker)
            {
                identifier = string.Empty;
                return false;
            }

            return true;
        }

        public void Apply(byte[] romData)
        {
            foreach (var patch in patches)
            {
                var index = FindPattern(romData, patch.Marker, patch.MarkerMask);
                if (index < 0 || romData.Length - index < patch.Replace.Length)
                {
                    throw new InvalidOperationException("One of the patch patterns could not be applied.");
                }

                patch.Replace.CopyTo(romData, index);
            }
        }
    }
}

